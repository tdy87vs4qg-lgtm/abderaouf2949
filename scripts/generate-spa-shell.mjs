// ============================================================================
// generate-spa-shell.mjs
//
// The exterior (تيسير) is a Vite/React SPA. Its production `index.html` links
// to HASHED asset files (index-XXXX.js / index-XXXX.css) whose names change on
// every build. The Hono worker must return this exact shell HTML for the public
// routes (/, /login, /signup, /subscription) so React Router can boot and the
// browser loads the correct hashed assets.
//
// Cloudflare Workers cannot read files at runtime (no fs), so we snapshot the
// freshly-built shell into a TypeScript module the worker imports at build time.
//
// Flow (see package.json):
//   1. build:frontend  → emits public/react/index.html + hashed assets
//   2. build:shell     → THIS script reads that index.html and writes
//                        src/generated/spa-shell.ts
//   3. build (server)  → bundles the worker, inlining the shell string
// ============================================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')

const htmlPath = resolve(root, 'public/react/index.html')
const outPath = resolve(root, 'src/generated/spa-shell.ts')

let html
try {
  html = readFileSync(htmlPath, 'utf8')
} catch (err) {
  console.error(
    `[generate-spa-shell] Could not read ${htmlPath}. ` +
      `Run the frontend build first (npm run build:frontend).`
  )
  throw err
}

// Escape backticks and ${ so the HTML is safe inside a TS template literal.
const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

const banner =
  '// AUTO-GENERATED by scripts/generate-spa-shell.mjs — DO NOT EDIT BY HAND.\n' +
  '// Snapshot of the built تيسير (exterior) SPA shell served for public routes.\n'

const body = `${banner}export const spaShell = \`${escaped}\`\n`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, body, 'utf8')

console.log(`[generate-spa-shell] Wrote ${outPath} (${html.length} bytes of HTML).`)
